import { getClientTimezoneInfo } from '../utils/timeFormat';

interface TooltipEntry {
  dataKey?: string | number;
  name?: string;
  value?: number | string;
  color?: string;
  payload?: Record<string, unknown>;
}

interface ExplainableTooltipProps {
  active?: boolean;
  payload?: TooltipEntry[];
  label?: string;
  context?: 'residual' | 'weather' | 'hdd' | 'wind_forecast' | 'carbon' | 'storage';
}

const PLAIN_ENGLISH_HINTS: Record<string, string> = {
  consumption: 'Total electricity being used across Finland right now.',
  residualLoad: 'Demand left over after wind power—covered by nuclear, hydro, or imports.',
  wind: 'Clean electricity generated by Finnish wind turbines.',
  nuclear: 'Steady, zero-carbon baseload power from Finnish nuclear reactors.',
  temperature: 'Outdoor air temperature driving electric space-heating demand.',
  windSpeed100m: 'Wind speed at turbine hub height (100m); ~3–25 m/s generates power.',
  actualConsumption: 'Actual measured electricity demand on the Finnish grid.',
  predictedConsumption: 'Demand estimated by our weather-based Heating Degree Day model.',
  actualWindMW: 'Measured national wind power generation from Fingrid.',
  predictedWindMW: 'Wind power predicted from Vaasa/Oulu coastal 100m wind speeds.',
  fittedWindMW: 'Theoretical turbine fleet curve at this wind speed.',
  actualResidualMW: 'Actual net demand remaining after wind generation.',
  predictedResidualMW: 'Projected net demand (Forecasted Load minus Forecasted Wind).',
  carbonIntensity: 'Grams of CO₂ emitted per kWh of electricity consumed (lower = cleaner grid).',
  originalResidual: 'Grid demand before any battery intervention.',
  shavedResidual: 'Smoothed grid demand after the battery discharges during peaks.',
};

export function ExplainableTooltip({
  active,
  payload,
  label,
  context = 'residual',
}: ExplainableTooltipProps) {
  if (!active || !payload || payload.length === 0) return null;

  const row = payload[0]?.payload ?? {};
  const isForecast = Boolean(row.isForecast);
  const { shortName } = getClientTimezoneInfo();
  const summary = buildTakeaway(context, row);

  return (
    <div className="bg-slate-950/95 border border-slate-700 rounded-xl p-3.5 shadow-xl max-w-xs text-xs space-y-2.5 backdrop-blur">
      <div className="flex items-center justify-between gap-2 border-b border-slate-800 pb-1.5">
        <span className="font-semibold text-slate-100">
          {label} ({shortName})
        </span>
        <span
          className={`px-2 py-0.5 rounded text-[10px] font-medium ${
            isForecast
              ? 'bg-amber-500/20 text-amber-300 border border-amber-500/40'
              : 'bg-emerald-500/20 text-emerald-300 border border-emerald-500/40'
          }`}
        >
          {isForecast ? '48h Forecast' : 'Measured Data'}
        </span>
      </div>

      <div className="space-y-2">
        {payload.map((entry, idx) => {
          const key = String(entry.dataKey ?? '');
          const numVal = typeof entry.value === 'number' ? entry.value : Number(entry.value);
          const formattedVal = Number.isFinite(numVal)
            ? numVal.toLocaleString(undefined, { maximumFractionDigits: 1 })
            : String(entry.value ?? '—');

          return (
            <div key={`${key}-${idx}`} className="space-y-0.5">
              <div className="flex items-center justify-between gap-3">
                <span className="flex items-center gap-1.5 text-slate-200 font-medium">
                  <span
                    className="w-2.5 h-2.5 rounded-full inline-block shrink-0"
                    style={{ backgroundColor: entry.color }}
                  />
                  {entry.name}
                </span>
                <span className="font-mono font-semibold text-white">{formattedVal}</span>
              </div>
              {PLAIN_ENGLISH_HINTS[key] && (
                <p className="text-[11px] text-slate-400 pl-4 leading-snug">
                  {PLAIN_ENGLISH_HINTS[key]}
                </p>
              )}
            </div>
          );
        })}
      </div>

      {summary && (
        <div className="bg-slate-900 border border-slate-800 rounded-lg p-2 text-[11px] text-emerald-300 leading-snug">
          💡 {summary}
        </div>
      )}
    </div>
  );
}

function buildTakeaway(context: string, row: Record<string, unknown>): string | null {
  if (context === 'residual') {
    const load = Number(row.consumption);
    const wind = Number(row.wind);
    if (Number.isFinite(load) && Number.isFinite(wind) && load > 0) {
      const share = ((wind / load) * 100).toFixed(1);
      return `Wind power supplies ${share}% of Finland's electricity during this hour.`;
    }
  }

  if (context === 'weather') {
    const temp = Number(row.temperature);
    if (Number.isFinite(temp)) {
      return temp < 0
        ? `Sub-zero (${temp}°C) temperatures increase electric heating demand across homes and district grids.`
        : `Mild temperature (${temp}°C) keeps space-heating electricity demand moderate.`;
    }
  }

  if (context === 'hdd') {
    const pred = Number(row.predictedConsumption);
    const actual = Number(row.actualConsumption);
    if (Number.isFinite(pred) && Number.isFinite(actual)) {
      const diff = Math.round(pred - actual);
      return `Model estimate is within ${Math.abs(diff).toLocaleString()} MW of actual grid load.`;
    }
    if (Number.isFinite(pred)) {
      return `Projected demand based on forecasted outdoor temperature.`;
    }
  }

  if (context === 'wind_forecast') {
    const predW = Number(row.predictedWindMW);
    const predR = Number(row.predictedResidualMW);
    if (Number.isFinite(predW) && Number.isFinite(predR)) {
      return `Projected wind (${predW.toLocaleString()} MW) leaves ${predR.toLocaleString()} MW of net load for dispatchable power.`;
    }
  }

  if (context === 'carbon') {
    const g = Number(row.carbonIntensity);
    if (Number.isFinite(g)) {
      if (g < 40) return 'Very clean grid hour—ideal time to charge EVs or run heavy appliances.';
      if (g < 90) return 'Moderate carbon intensity—clean generation is supplemented by imports/peakers.';
      return 'Higher carbon hour—shifting flexible electricity use away from this hour cuts CO₂.';
    }
  }

  if (context === 'storage') {
    const orig = Number(row.originalResidual);
    const shaved = Number(row.shavedResidual);
    if (Number.isFinite(orig) && Number.isFinite(shaved)) {
      const delta = Math.round(orig - shaved);
      if (delta > 0) return `Battery is discharging ${delta} MW to shave the grid peak.`;
      if (delta < 0) return `Battery is charging (${Math.abs(delta)} MW) during low-demand surplus hours.`;
      return 'Battery is on standby—grid demand is within normal range.';
    }
  }

  return null;
}
