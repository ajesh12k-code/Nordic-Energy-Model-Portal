/** Geographic coordinates and display metadata for monitored Finnish cities. */
export interface CityLocation {
  key: string;
  name: string;
  lat: number;
  lon: number;
}

/** Metadata descriptor stored in catalog.json for each ingested dataset. */
export interface DatasetMetadata {
  slug: string;
  title: string;
  provider: string;
  source_id: string;
  unit: string;
  category: 'demand' | 'generation' | 'weather' | 'emissions' | 'transmission' | string;
  description: string;
  license: string;
  resolution: string;
  updated_at_utc: string;
  record_count: number;
  file_path: string;
  locations?: CityLocation[];
}

/** Top-level manifest listing all datasets generated by the hourly pipeline. */
export interface CatalogManifest {
  generated_at_utc: string;
  dataset_count: number;
  datasets: DatasetMetadata[];
}

/** Single hourly observation or forecast point inside a dataset JSON file. */
export interface TimeSeriesPoint {
  timestamp: string;
  value: number;
  samples: number;
  by_city?: Record<string, number>;
}

/** Full JSON structure of an individual dataset file under public/data/. */
export interface DatasetPayload {
  metadata: DatasetMetadata;
  data: TimeSeriesPoint[];
}

/** Unified hourly record aligning Finland, Denmark, and cross-border Nordic flows. */
export interface MergedHourlyRecord {
  timestamp: string;
  label: string;
  // Finland core grid
  consumption?: number;
  totalProduction?: number;
  wind?: number;
  nuclear?: number;
  hydro?: number;
  chpTotal?: number;
  otherGeneration?: number;
  netImport?: number;
  residualLoad?: number;
  carbonIntensity?: number;
  // Bilateral Nordic/Baltic interconnectors (+ = import to FI, - = export from FI)
  flowSE1?: number;
  flowSE3?: number;
  flowNO4?: number;
  flowEE?: number;
  // Denmark (DK1 + DK2 via Energinet)
  dkConsumption?: number;
  dkWind?: number;
  dkSolar?: number;
  dkCarbonIntensity?: number;
  // Meteorology
  temperature?: number;
  windSpeed100m?: number;
  temp_helsinki?: number;
  temp_tampere?: number;
  temp_lappeenranta?: number;
  temp_vaasa?: number;
  temp_oulu?: number;
  wind_helsinki?: number;
  wind_tampere?: number;
  wind_lappeenranta?: number;
  wind_vaasa?: number;
  wind_oulu?: number;
  isForecast: boolean;
}
