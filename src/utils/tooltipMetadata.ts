/** Infers the appropriate physical unit for static or dynamic city-prefixed series keys. */
export function inferMetricUnit(key: string, name?: string): string {
  if (METRIC_META[key]?.unit) return METRIC_META[key].unit;
  if (key.startsWith('temp_')) return '°C';
  if (key.startsWith('wind_')) return 'm/s';
  if (name?.includes('(°C)')) return '°C';
  if (name?.includes('(m/s)')) return 'm/s';
  if (name?.includes('(MW)')) return 'MW';
  return '';
}

/** Generates a single-sentence contextual insight for the hovered data point. */
export function buildTooltipTakeaway(context: string, row: Record<string, unknown>): string | null {
  if (context === 'carbon') {
    const g = Number(row.carbonIntensity);
    const share = Number(row.windSharePct);
    if (Number.isFinite(g) && Number.isFinite(share)) {
      const rating = g < 40 ? 'ultra-clean hour' : g < 90 ? 'moderately clean' : 'higher-emission hour';
      return `When wind supplies ${share}% of demand, grid emissions drop to ${g} gCO₂/kWh (${rating}).`;
    }
    if (Number.isFinite(g)) {
      return g < 40
        ? 'Very clean grid hour—ideal time to charge EVs or run heavy appliances.'
        : 'Shifting flexible electricity use away from higher-emission hours cuts CO₂.';
    }
  }

  if (context === 'residual') {
    const load = Number(row.consumption);
    const prod = Number(row.totalProduction);
    if (Number.isFinite(load) && Number.isFinite(prod) && load > 0) {
      const balance = Math.round(prod - load);
      const flowText =
        balance >= 0
          ? `domestic generation exceeds demand by +${balance.toLocaleString('en-US')} MW (net export)`
          : `domestic generation is ${Math.abs(balance).toLocaleString('en-US')} MW below demand (covered by net imports)`;
      return `Power balance: ${flowText}.`;
    }
  }

  if (context === 'wind_forecast') {
    const ws = Number(row.windSpeedMs);
    const actualW = Number(row.actualWindMW);
    if (Number.isFinite(ws) && Number.isFinite(actualW)) {
      return `At ${ws} m/s corridor wind speed, Finland's turbine fleet generated ${actualW.toLocaleString('en-US')} MW.`;
    }
    const predW = Number(row.predictedWindMW);
    const predR = Number(row.predictedResidualMW);
    if (Number.isFinite(predW) && Number.isFinite(predR)) {
      return `Projected wind (${predW.toLocaleString('en-US')} MW) leaves ${predR.toLocaleString('en-US')} MW for hydro, nuclear, CHP, or imports.`;
    }
  }

  if (context === 'storage') {
    const orig = Number(row.originalResidual);
    const shaved = Number(row.shavedResidual);
    if (Number.isFinite(orig) && Number.isFinite(shaved)) {
      const delta = Math.round(orig - shaved);
      if (delta > 0) return `Battery is discharging ${delta} MW to shave the grid peak.`;
      if (delta < 0) return `Battery is charging (${Math.abs(delta)} MW) during low-demand surplus hours.`;
      return 'Battery is on standby—grid demand is within normal range.';
    }
  }

  return null;
}
